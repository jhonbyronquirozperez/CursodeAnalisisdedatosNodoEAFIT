from pathlib import Path

import pandas as pd

# ============================================================
# CAMBIA ESTA LÍNEA: un archivo .csv o una carpeta con varios
RUTA = "/content/entrega_con_errores.csv"
# ============================================================

COLUMNAS = ["id_inscripcion", "nombre", "documento", "edad", "genero", "ciudad",
            "colegio", "deporte", "fecha_inscripcion", "correo", "telefono"]

# Valores esperados según la clave (por documento)
FECHAS = {
    "1034567890": "2026-10-01", "1029876543": "2026-10-01", "1031122334": "2026-10-02",
    "1035566778": "2026-10-02", "1037788990": "2026-10-02", "1038899001": "2026-10-02",
    "1030011223": "2026-10-03", "1032233445": "2026-10-03", "1034455667": "2026-10-03",
    "1036677889": "2026-10-04", "1037788001": "2026-10-04", "1038899112": "2026-10-05",
    "1039900223": "2026-10-05", "1030123456": "2026-10-06",
}
CORREOS_INVALIDOS = {  # no se deben "inventar": quedan igual o vacíos
    "1035566778": "juanpablo.arango.correo.com",
    "1032233445": "",
    "1039900223": "salome.a@correo",
}


def leer(ruta):
    """Lee el CSV sin cambiar nada. Detecta si el separador no es coma."""
    texto = ruta.read_bytes()
    try:
        texto.decode("utf-8")
        utf8 = True
    except UnicodeDecodeError:
        utf8 = False
    df = pd.read_csv(ruta, sep=None, engine="python", dtype=str,
                     keep_default_na=False, encoding="utf-8" if utf8 else "latin-1")
    primera_linea = texto.splitlines()[0].decode("utf-8", errors="ignore")
    con_comas = primera_linea.count(",") >= len(COLUMNAS) - 1
    df.columns = [c.strip().lstrip("﻿") for c in df.columns]
    return df, utf8, con_comas


def revisar(ruta):
    reglas = []

    def regla(nombre, ok, detalle=""):
        reglas.append({"archivo": ruta.name, "regla": nombre,
                       "cumple": bool(ok), "detalle": "" if ok else detalle})

    try:
        df, utf8, con_comas = leer(ruta)
    except Exception as e:  # el archivo ni siquiera abre
        regla("El archivo abre como CSV", False, str(e))
        return reglas

    regla("Codificación UTF-8", utf8, "El archivo no está en UTF-8: las tildes se pueden dañar")
    regla("Separado por comas", con_comas, "El separador no es la coma (¿punto y coma?)")

    faltan = [c for c in COLUMNAS if c not in df.columns]
    regla("Conserva las 11 columnas originales", not faltan, f"Faltan: {', '.join(faltan)}")
    if faltan:
        return reglas

    doc = df["documento"].str.strip()
    regla("Tiene 14 filas", len(df) == 14, f"Tiene {len(df)} filas")
    regla("Sin filas duplicadas", not df[COLUMNAS].duplicated().any(),
          f"{df[COLUMNAS].duplicated().sum()} filas repetidas")
    regla("Documento solo con dígitos", doc.str.fullmatch(r"\d+").all(),
          f"Con otros caracteres: {', '.join(doc[~doc.str.fullmatch(r'\d+')])}")
    regla("Sin documentos repetidos", not doc.duplicated().any(),
          f"Repetidos: {', '.join(doc[doc.duplicated()].unique())}")
    regla("Se conservó la primera inscripción de Valentina (id 1, no id 10)",
          "10" not in df["id_inscripcion"].str.strip().tolist(), "Quedó la inscripción con id 10")

    nombre = df["nombre"]
    malos = nombre[(nombre != nombre.str.strip()) | nombre.str.contains("  ") | (nombre != nombre.str.title())]
    regla("Nombres sin espacios de más y en formato nombre propio", malos.empty,
          f"Revisar: {', '.join(malos)}")

    edad = df["edad"].str.strip()
    no_num = edad[(edad != "") & ~edad.str.fullmatch(r"\d+")]
    regla("Edad numérica o vacía", no_num.empty, f"Valores no numéricos: {', '.join(no_num)}")
    edades = pd.to_numeric(edad, errors="coerce")
    regla("Sin edades imposibles", not ((edades < 5) | (edades > 100)).any(),
          f"Edades fuera de rango: {', '.join(edad[(edades < 5) | (edades > 100)])}")
    sara = df.loc[doc == "1030011223", "edad"].str.strip()
    regla("La edad 150 quedó vacía (no se adivinó)", (sara == "").all() and len(sara) == 1,
          f"Sara Montoya tiene edad '{', '.join(sara)}'")
    jero = df.loc[doc == "1030123456", "edad"].str.strip()
    regla("El inscrito de 18 años no se borró ni se cambió", (jero == "18").all() and len(jero) == 1,
          "Jerónimo Castaño fue eliminado o su edad cambió")

    for col, permitidos in [("genero", {"F", "M"}),
                            ("ciudad", {"Bello", "Envigado", "Itagüí", "Medellín"}),
                            ("deporte", {"Baloncesto", "Fútbol", "Voleibol"})]:
        extra = set(df[col].str.strip()) - permitidos
        regla(f"{col}: solo valores unificados", not extra, f"Valores de más: {', '.join(sorted(extra))}")
    n_col = df["colegio"].str.strip().nunique()
    regla("colegio: 3 valores distintos", n_col == 3, f"Hay {n_col} valores distintos")

    fechas = df["fecha_inscripcion"].str.strip()
    no_iso = fechas[~fechas.str.fullmatch(r"\d{4}-\d{2}-\d{2}")]
    regla("Fechas en formato AAAA-MM-DD", no_iso.empty, f"No ISO: {', '.join(no_iso)}")
    malas = [f"{d}: {f} (debía ser {FECHAS[d]})" for d, f in zip(doc, fechas)
             if d in FECHAS and f != FECHAS[d]]
    regla("Fechas correctas (día y mes sin invertir)", not malas, "; ".join(malas))

    tel = df["telefono"].str.strip()
    regla("Teléfono con 10 dígitos", tel.str.fullmatch(r"\d{10}").all(),
          f"Revisar: {', '.join(tel[~tel.str.fullmatch(r'\d{10}')])}")

    inventados = []
    for d, original in CORREOS_INVALIDOS.items():
        actual = df.loc[doc == d, "correo"].str.strip()
        if len(actual) and actual.iloc[0] not in (original, ""):
            inventados.append(f"{d}: '{actual.iloc[0]}'")
    regla("No se inventaron correos", not inventados, "; ".join(inventados))

    return reglas


def main():
    ruta = Path(RUTA)
    if ruta.is_file():
        archivos, carpeta = [ruta], ruta.parent
    elif ruta.is_dir():
        archivos = sorted(p for p in ruta.glob("*.csv") if p.name != "resultados_revision.csv")
        carpeta = ruta
    else:
        print("No encontré el archivo o la carpeta:", ruta.resolve())
        return
    if not archivos:
        print("No encontré archivos .csv en", ruta.resolve())
        return
    todas = []
    for ruta in archivos:
        reglas = revisar(ruta)
        todas += reglas
        cumple = sum(r["cumple"] for r in reglas)
        nota = round(1 + 4 * cumple / len(reglas), 1)
        print(f"\n{ruta.name}: {cumple}/{len(reglas)} reglas · nota sugerida {nota}")
        for r in reglas:
            if not r["cumple"]:
                print(f"   ✘ {r['regla']}: {r['detalle']}")
    pd.DataFrame(todas).to_csv(carpeta / "resultados_revision.csv", index=False, encoding="utf-8")
    print(f"\nDetalle guardado en {carpeta / 'resultados_revision.csv'}")


if __name__ == "__main__":
    main()
